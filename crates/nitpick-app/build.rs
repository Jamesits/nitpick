use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::Command;

use cxx_qt_build::{CxxQtBuilder, QmlModule};

/// Shaders compiled with `qsb` and embedded into a generated C++ header.
const SHADERS: [(&str, &str); 2] = [
    ("shaders/pattern.vert", "kPatternVertQsb"),
    ("shaders/pattern.frag", "kPatternFragQsb"),
];

fn qmake() -> String {
    std::env::var("QMAKE").unwrap_or_else(|_| "qmake".into())
}

fn qmake_query(var: &str) -> String {
    let out = Command::new(qmake())
        .args(["-query", var])
        .output()
        .unwrap_or_else(|e| panic!("cannot run qmake (set QMAKE): {e}"));
    String::from_utf8_lossy(&out.stdout).trim().to_owned()
}

/// Include directories of the Qt private headers. `QRhi` lives in
/// `<module>/<version>/<module>/rhi`; the swap chain internals that HDR
/// metadata needs are in `<module>/<version>/<module>/private`. Frameworks
/// (macOS) keep them under `<module>.framework/Headers/<version>`.
fn private_include_dirs() -> Vec<PathBuf> {
    let version = qmake_query("QT_VERSION");
    let headers = PathBuf::from(qmake_query("QT_INSTALL_HEADERS"));
    let libs = PathBuf::from(qmake_query("QT_INSTALL_LIBS"));
    let mut dirs = Vec::new();
    for module in ["QtCore", "QtGui"] {
        let candidates = [
            headers.join(module).join(&version),
            libs.join(format!("{module}.framework"))
                .join("Headers")
                .join(&version),
        ];
        for base in candidates.into_iter().filter(|d| d.is_dir()) {
            dirs.push(base.join(module));
            dirs.push(base);
        }
    }
    assert!(
        !dirs.is_empty(),
        "Qt {version} private headers not found under {}",
        headers.display()
    );
    dirs
}

fn qsb() -> PathBuf {
    let name = if cfg!(windows) { "qsb.exe" } else { "qsb" };
    ["QT_HOST_BINS", "QT_HOST_LIBEXECS"]
        .iter()
        .map(|v| PathBuf::from(qmake_query(v)).join(name))
        .find(|p| p.is_file())
        .unwrap_or_else(|| panic!("{name} not found; install the Qt Shader Tools module"))
}

/// Compiles the shaders for D3D11 (HLSL 5.0), Metal (MSL 1.2) and Vulkan
/// (SPIR-V, always included) and writes them as byte arrays to
/// `<out>/nitpick-shaders/pattern_shaders.h`.
fn compile_shaders(out: &Path) -> PathBuf {
    let dir = out.join("nitpick-shaders");
    std::fs::create_dir_all(&dir).expect("create shader output directory");
    let qsb = qsb();
    let mut header = String::from("#pragma once\n// Generated by build.rs from shaders/.\n\n");
    for (src, symbol) in SHADERS {
        println!("cargo::rerun-if-changed={src}");
        let file = Path::new(src).file_name().expect("shader file name");
        let target = dir.join(file).with_extension(format!(
            "{}.qsb",
            Path::new(src).extension().unwrap().to_string_lossy()
        ));
        let status = Command::new(&qsb)
            .args(["--hlsl", "50", "--msl", "12", "-o"])
            .arg(&target)
            .arg(src)
            .status()
            .expect("run qsb");
        assert!(status.success(), "qsb failed for {src}");
        let bytes = std::fs::read(&target).expect("read qsb output");
        let list: Vec<String> = bytes.iter().map(|b| format!("0x{b:02x}")).collect();
        let _ = writeln!(
            header,
            "inline constexpr unsigned char {symbol}[] = {{{}}};",
            list.join(",")
        );
    }
    std::fs::write(dir.join("pattern_shaders.h"), header).expect("write shader header");
    dir
}

fn main() {
    let out = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    let shader_dir = compile_shaders(&out);
    let private_dirs = private_include_dirs();
    let target_os = std::env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();

    let mut builder =
        CxxQtBuilder::new_qml_module(QmlModule::new("nitpick").qml_file("qml/main.qml"))
            .qt_module("Gui")
            .files(["src/launcher.rs", "src/display.rs"])
            .cpp_file("cpp/pattern_window.cpp");
    if target_os == "macos" {
        builder = builder.cpp_file("cpp/metal_hdr.mm");
    }
    // SAFETY: only adds include directories to the C++ build.
    let builder = unsafe {
        builder.cc_builder(|cc| {
            cc.include(&shader_dir);
            for dir in &private_dirs {
                cc.include(dir);
            }
        })
    };
    builder.build();

    match target_os.as_str() {
        "windows" => {
            println!("cargo::rustc-link-lib=d3d11");
            println!("cargo::rustc-link-lib=dxgi");
            println!("cargo::rustc-link-lib=user32");
        }
        "macos" => {
            println!("cargo::rustc-link-lib=framework=QuartzCore");
            println!("cargo::rustc-link-lib=framework=AppKit");
        }
        _ => {}
    }
}
